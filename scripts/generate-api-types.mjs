// Generates src/api/generated/{openapi.json,schema.d.ts} from the running backend.
// Usage: npm run api:types   (API must be up: cd backend && docker compose up -d)
import { mkdir, writeFile } from "node:fs/promises"
import openapiTS, { astToString } from "openapi-typescript"

const base = process.env.NEXT_PUBLIC_API_BASE_URL ?? "http://localhost:8000"
const outDir = new URL("../src/api/generated/", import.meta.url)

let schema
try {
  const res = await fetch(`${base}/openapi.json`)
  if (!res.ok) throw new Error(`status ${res.status}`)
  schema = await res.json()
} catch (error) {
  console.error(`Could not fetch ${base}/openapi.json (${error}).`)
  console.error("Start the API first: cd backend && docker compose up -d")
  process.exit(1)
}

const header =
  "// Generated by scripts/generate-api-types.mjs from the backend OpenAPI schema.\n" +
  "// Do not edit. Regenerate with: npm run api:types\n\n"

await mkdir(outDir, { recursive: true })
await writeFile(
  new URL("openapi.json", outDir),
  `${JSON.stringify(schema, null, 2)}\n`,
)
await writeFile(
  new URL("schema.d.ts", outDir),
  header + astToString(await openapiTS(schema)),
)
console.log(`API types written to src/api/generated from ${base}/openapi.json`)
